// ── Content-based deterministic image helper (mirrors fertilizers.ts) ─────
const slugify = (s: string) =>
  s.toLowerCase().replace(/[^a-z0-9\s,]/g, "").trim().replace(/\s+/g, ",");
const img = (q: string, w = 1200, h = 800) => aiImageFromTags(slugify(q), w, h);

function buildImages(
  slug: string,
  keywords: string[],
  crop0: string,
  soil0: string,
  form: Form,
  cat: FertilizerCategory,
): Fertilizer["images"] {
  const key = keywords[0] ?? slug;
  const crop = crop0.toLowerCase();
  const soil = soil0.toLowerCase();
  return {
    hero: img(
      `${slug},${key},${cat} fertilizer,${form} form,product bag on indian farm field`,
    ),
    packaging: [
      img(`${key},fertilizer,bag,package`),
      img(`${key},sack,warehouse`),
      img(`${key},retail,farm,shop`),
      img(`${key},bulk,storage`),
    ],
    granules: img(`${key},${form.toLowerCase()},macro,closeup`),
    application: [
      img(`${key},field,application,farmer`),
      img(`tractor,fertilizer,spreader`),
      img(`${cat.toLowerCase()},application,farm`),
      img(`drip,irrigation,fertigation,${crop}`),
      img(`foliar,spray,${crop}`),
    ],
    label: img(`fertilizer,label,${key},bag`),
    cropApplication: [],
    beforeAfter: {
      before: img(`${crop},yellow,leaves,deficiency`),
      after: img(`${crop},green,healthy,field`),
    },
    soil: img(`${soil},soil,texture,farm`),
    root: img(`plant,root,system,soil`),
    deficiency: img(`${key},nutrient,deficiency,plant`),
    storage: img(`fertilizer,warehouse,storage`),
    safety: img(`farmer,safety,gloves,mask`),
    gallery: [
      img(`${key},farm,india`),
      img(`${key},agriculture,closeup`),
      img(`${key},${cat.toLowerCase()},farming`),
      img(`fertilizer,drone,spray`),
      img(`hand,holding,fertilizer,soil`),
      img(`${crop},harvest,yield`),
    ],
  };
}

// Compact factory — every field is either passed or defaulted sensibly.
type QuickOpts = Partial<Omit<Fertilizer, "slug" | "name" | "images">>;
function q(
  slug: string,
  name: string,
  cat: FertilizerCategory,
  form: Form,
  npk: [number, number, number],
  price: [string, number],
  mfr: string[],
  crops: string[],
  soils: string[],
  methods: ApplicationMethod[],
  dose: [number, number],
  stage: string,
  benefits: string[],
  keywords: string[] = [],
  extra: QuickOpts = {},
): Fertilizer {
  const kw = keywords.length ? keywords : [name.toLowerCase()];
  const images = buildImages(slug, kw, crops[0] ?? "crop", soils[0] ?? "loam", form, cat);
  images.cropApplication = crops.slice(0, 6).map((c) => ({
    crop: c,
    url: img(`${c.toLowerCase()},crop,field,healthy,${kw[0]}`),
  }));
  return {
    slug,
    name,
    generic: extra.generic ?? name,
    brand: extra.brand,
    category: cat,
    form,
    formula: extra.formula ?? "-",
    npk: { n: npk[0], p: npk[1], k: npk[2] },
    secondary: extra.secondary,
    micro: extra.micro,
    color: extra.color ?? "Off-white",
    price: { unit: price[0], inr: price[1] },
    subsidy: extra.subsidy,
    shelfLifeMonths: extra.shelfLifeMonths ?? 24,
    storage: extra.storage ?? "Cool, dry, sealed away from moisture",
    suitableCrops: crops,
    unsuitableCrops: extra.unsuitableCrops,
    suitableSoils: soils,
    applicationMethods: methods,
    dosagePerAcreKg: { min: dose[0], max: dose[1] },
    stage,
    benefits,
    cautions: extra.cautions ?? [],
    mixing: extra.mixing ?? "-",
    manufacturers: mfr,
    govApproved: extra.govApproved ?? true,
    images,
  };
}

