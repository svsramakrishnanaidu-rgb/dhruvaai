type Spec = {
  slug: string;
  name: string;
  sci: string;
  emoji: string;
  category: CropCategory;
  img: ImgKey;
  family: string;
  season: string;
  durationDays: number;
  districts: string[];        // suitable districts (real, per crop)
  climate: string;
  temperature: string;        // "20-30°C"
  rainfall: string;           // "600-1000 mm"
  soilType: string;
  soilPh: string;
  waterNeed: "Low" | "Medium" | "High";
  profitPct: number;
  yieldStr: string;           // e.g. "18-22 q/acre"
  seedRate: string;
  seedTreatment: string;
  spacing: string;
  sowingMethod: string;
  irrigation: string[];
  fertilizer: FertilizerDose[];
  weeds: string[];
  diseases: Disease[];
  pests: string[];
  harvesting: string;
  storage: string;
  price: number;              // ₹ per unit
  msp: number;
  unit: string;               // "quintal" | "kg" | "tonne"
  rotation: RotationItem[];
  tips: string[];
  precautions: string[];
  tags?: string[];
  desc: string;
  trending?: boolean;
};

function trend(base: number): { day: string; price: number }[] {
  // Deterministic pseudo-trend so charts look natural without RNG per render.
  const days = ["Mon","Tue","Wed","Thu","Fri","Sat","Sun"];
  return days.map((d, i) => ({ day: d, price: Math.round(base * (0.94 + ((i * 37) % 13) / 100)) }));
}

function make(s: Spec): Crop {
  return {
    slug: s.slug,
    name: s.name,
    scientificName: s.sci,
    image: IMG[s.img],
    emoji: s.emoji,
    season: s.season,
    suitableDistricts: s.districts,
    climate: s.climate,
    temperature: s.temperature,
    rainfall: s.rainfall,
    soilType: s.soilType,
    soilPh: s.soilPh,
    waterNeed: s.waterNeed,
    profitPct: s.profitPct,
    yield: s.yieldStr,
    trending: !!s.trending,
    landPrep: defaultLandPrep,
    seedRate: s.seedRate,
    seedTreatment: s.seedTreatment,
    spacing: s.spacing,
    sowingMethod: s.sowingMethod,
    irrigation: s.irrigation,
    fertilizer: s.fertilizer,
    weeds: s.weeds,
    diseases: s.diseases,
    pests: s.pests,
    harvesting: s.harvesting,
    storage: s.storage,
    marketPrice: { unit: s.unit, price: s.price, msp: s.msp, trend: trend(s.price) },
    rotation: s.rotation,
    tips: s.tips,
    precautions: s.precautions,
    references: [
      { label: "ICAR Package of Practices", url: "https://icar.org.in" },
      { label: "AgMarknet", url: "https://agmarknet.gov.in" },
    ],
    category: s.category,
    family: s.family,
    description: s.desc,
    durationDays: s.durationDays,
    tags: s.tags,
  };
}

